#!/usr/bin/env python3
"""board_export.py: export ONE business line from a sanitized board as shareable markdown.

Entity separation is enforced at the export step: nothing from any other line, no run health, no
handled ids, no session names (they can name other projects), and no owner tokens. Use this for
anything that leaves your own screen.

Usage: board_export.py --line acme [--board data/snapshots/latest.json] [--out ~/Downloads/share-acme.md]
Default board = newest data/snapshots/*.json. Exit 0 ok, 3 unknown line.
"""

import argparse
import glob
import json
import os
import sys
from pathlib import Path

STATE_LABEL = {"needs_you": "Needs me", "waiting": "Waiting on them", "moving": "Moving", "parked": "Parked"}


def export_line(board, line_id):
    line = next((l for l in board.get("lines", []) if l.get("id") == line_id), None)
    if line is None:
        return None
    md = [f"# {line['name']} — status as of {board.get('generated_at', '')[:16].replace('T', ' ')}", ""]
    if line.get("headline"):
        md += [line["headline"], ""]
    if not line.get("items"):
        md.append("Nothing open right now.")
    for i in line.get("items", []):
        due = f" (due {i['due']})" if i.get("due") else ""
        owner = i.get("owner", "you")
        who = "" if owner == "you" else (" · Claude is on it" if owner == "claude" else f" · with {owner[5:]}" if owner.startswith("them:") else "")
        md.append(f"- **{STATE_LABEL.get(i['state'], i['state'])}: {i['title']}**{due}{who}")
        md.append(f"  {i['synopsis']}")
        if i.get("source_url"):
            md.append(f"  Source: {i['source_url']}")
    md.append("")
    md.append("_Scoped export: this line only. Generated by the owner's command board._")
    return "\n".join(md)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--line", required=True)
    ap.add_argument("--board")
    ap.add_argument("--out")
    args = ap.parse_args(argv)
    repo = Path(__file__).resolve().parent.parent
    board_path = args.board or (sorted(glob.glob(str(repo / "data" / "snapshots" / "*.json")), key=os.path.getmtime) or [None])[-1]
    if not board_path:
        print("ERROR: no board snapshot found", file=sys.stderr)
        return 3
    board = json.loads(Path(board_path).read_text())
    text = export_line(board, args.line)
    if text is None:
        print(f"ERROR: no line {args.line!r} in {board_path}; lines: {[l['id'] for l in board.get('lines', [])]}", file=sys.stderr)
        return 3
    out = Path(os.path.expanduser(args.out)) if args.out else Path(__file__).resolve().parent.parent / "out" / f"share-{args.line}-{board.get('generated_at', '')[:10]}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"wrote {out} ({len(text)} chars, {args.line} only)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
